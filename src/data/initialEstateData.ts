function makeSeedInvoice(params: {
  id: string;
  property: PropertyHouse;
  unit: Unit;
  tenant: TenantRecord;
  reading: UtilityReading;
  status: PaymentStatus;
  paidAt: string | null;
}): InvoiceRecord {
  const { id, property, unit, tenant, reading, status, paidAt } = params;
  const rentAmount = tenant.lease_type === 'Lease' ? 0 : tenant.monthly_rent;
  const cleaningFee = tenant.monthly_maintenance_charge;

  const houseMaint = INITIAL_HOUSE_MAINTENANCE.find(
    (m) => m.property_id === property.property_id && m.billing_month === reading.billing_month
  );
  const unitCount = INITIAL_UNITS.filter(
    (u) => u.property_id === property.property_id
  ).length;
  const bldgTotal = houseMaint?.total_house_maintenance ?? 0;
  const bldgShare =
    houseMaint && unitCount > 0 ? Math.round(bldgTotal / unitCount) : 0;
  const bldgItems = houseMaint
    ? [
        { name: 'Common Motor Electricity', amount: houseMaint.common_eb_amount },
        ...houseMaint.additional_charges.map((c) => ({
          name: c.charge_name,
          amount: c.charge_amount,
        })),
      ]
    : [];

  const totalBillValue =
    rentAmount + cleaningFee + bldgShare + reading.water_bill_amount + reading.eb_bill_amount;
  const totalPayableToOwner =
    rentAmount +
    cleaningFee +
    bldgShare +
    reading.water_bill_amount +
    (reading.eb_paid_to_owner ? reading.eb_bill_amount : 0);

  const amountPaid = status === 'Paid & Closed' ? totalPayableToOwner : 0;
  const balanceDue = Math.max(0, totalPayableToOwner - amountPaid);
  const isLocked = isInvoiceLockedStatus(status);

  return {
    id,
    property_id: property.property_id,
    property_name: property.property_name,
    unit_id: unit.unit_id,
    tenant_id: tenant.id,
    billing_month: reading.billing_month,
    unit_name: unit.unit_name,
    unit_type: unit.unit_type,
    floor: unit.floor,
    tenant_name: tenant.full_name,
    whatsapp_phone: tenant.whatsapp_phone,
    lease_type: tenant.lease_type,
    rent_amount: rentAmount,
    tenant_cleaning_fee: cleaningFee,
    building_maintenance_total: bldgTotal,
    building_unit_count: unitCount,
    building_maintenance_share: bldgShare,
    building_maintenance_items: bldgItems,
    eb_amount: reading.eb_bill_amount,
    eb_paid_to_owner: reading.eb_paid_to_owner,
    water_prev_1: reading.prev_reading_1,
    water_curr_1: reading.curr_reading_1,
    water_prev_2: reading.prev_reading_2,
    water_curr_2: reading.curr_reading_2,
    water_net_units: reading.net_consumption,
    water_rate: reading.water_rate,
    water_amount: reading.water_bill_amount,
    carried_forward_balance: 0,
    total_bill_value: totalBillValue,
    total_payable_to_owner: totalPayableToOwner,
    amount_paid: amountPaid,
    balance_due: balanceDue,
    payment_status: status,
    is_locked: isLocked,
    upi_link: buildUpiPaymentLink({
      upiId: DEFAULT_APP_SETTINGS.merchant_upi_id,
      payeeName: DEFAULT_APP_SETTINGS.merchant_name,
      amount: balanceDue > 0 ? balanceDue : totalPayableToOwner,
      note: `${id} ${property.property_name} ${unit.unit_name}`,
    }),
    due_date: `${reading.billing_month}-05`,
    generated_at: '2026-11-05T12:00:00Z',
    paid_at: paidAt,
    closed_at: isLocked ? paidAt || '2026-11-06' : null,
  };
}

